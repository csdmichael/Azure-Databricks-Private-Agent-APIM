import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..', '..');
const videosDirectory = resolve(repositoryRoot, 'foundry', 'docs', 'videos');
const metadataPath = resolve(videosDirectory, 'videos.json');
const outputPath = resolve(scriptDirectory, '..', 'src', 'app', 'showcase', 'foundry-videos.generated.ts');
const mediaRoot = 'assets/foundry/videos';

const metadata = JSON.parse(await readFile(metadataPath, 'utf8'));
const files = (await readdir(videosDirectory))
  .filter((file) => file.toLowerCase().endsWith('.mp4'))
  .sort((left, right) => {
    const orderDifference = (metadata[left]?.order ?? Number.MAX_SAFE_INTEGER) -
      (metadata[right]?.order ?? Number.MAX_SAFE_INTEGER);
    return orderDifference || left.localeCompare(right, undefined, { numeric: true });
  });

const missingFiles = Object.keys(metadata).filter((file) => !files.includes(file));
if (missingFiles.length) {
  throw new Error(`Foundry video metadata references missing files: ${missingFiles.join(', ')}`);
}

const videos = files.map((file, index) => {
  const details = metadata[file] ?? {};
  const fallbackTitle = file.replace(/\.mp4$/i, '').replace(/\s+/g, ' ').trim();

  return {
    sequence: String(index + 1).padStart(2, '0'),
    title: details.title ?? fallbackTitle,
    description: details.description ?? `Watch ${fallbackTitle}.`,
    duration: details.duration ?? 'Available now',
    file: `${mediaRoot}/${encodeURIComponent(file)}`,
  };
});

const source = `// Generated by scripts/generate-foundry-videos.mjs. Do not edit directly.
export const FOUNDRY_VIDEOS = ${JSON.stringify(videos, null, 2)} as const;
`;

await writeFile(outputPath, source, 'utf8');
console.log(`Generated ${videos.length} Foundry video${videos.length === 1 ? '' : 's'}.`);
